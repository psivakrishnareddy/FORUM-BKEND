export class Agency {
    /**
     * @type {Number} The Agency Id
     */
    agencyId;

    /**
     * @type {String} The Agency Name
     */
    agencyName;

    /**
     * @type {String} Updated at timestamp
     */
    updatedAt;

    /**
     * @type {String} Created at Timestamp
     */
    createdAt;

    /**
     * @type {String} Type of Agency
     */
    agencyType;

    /**
     * @type {Boolean} Is Leaf of Agency
     */
    leaf;

    /**
     * @type {Boolean} Is the Agency Active
     */
    isActive;

    /**
     * @type {Number} The Agency code
     */
    agencyCode;

    /**
     * @type {Number} The Agency Group Id
     */
    agencyGroupId;

    /**
     * @type {Boolean} Is self Agency
     */
    isSelf;

    /**
     * @type {String} The Street Address of the agency
     */
    streetaddress;

    /**
     * @type {String} The city of the agency
     */
    city;

    /**
     * @type {String} The state of the Agency
     */
    state;

    /**
     * @type {Number} The Zipcode of the Agency
     */
    zipcode;
}